#!/usr/bin/env node
"use strict";

import { readFile, readdir, stat } from "node:fs/promises";
import path from "node:path";
import { computeServiceWorkerCoreDigest } from "../../scripts/release-lib.mjs";
import { ROOT, requireRun, writeJson } from "./lib.mjs";

const BASE_COMMIT = process.env.UPDATE20_BASE_COMMIT || "9b5ebf1d3e383a9345df8a5d8b12333df447f7ad";
const NEW_VERSION = "1.4.0";
const failures = [];
const packageJson = JSON.parse(await readFile(path.join(ROOT, "package.json"), "utf8"));
const lock = JSON.parse(await readFile(path.join(ROOT, "package-lock.json"), "utf8"));
const docsFacts = await readFile(path.join(ROOT, "docs/DOCUMENTATION-CONSISTENCY.md"), "utf8");
const browserReadme = await readFile(path.join(ROOT, "browser/README.md"), "utf8");
const standalone = {};
for (const relativePath of ["browser/standalone/pastafari-date.js", "browser/standalone/pastafari-date.min.js"]) {
  const current = await readFile(path.join(ROOT, relativePath), "utf8");
  const old = requireRun("git", ["show", `${BASE_COMMIT}:${relativePath}`], { timeoutMs: 60_000 }).stdout;
  const oldHeader = "/*! Pastafari Calendar v1.3.0 | standalone classic-script build | generated by npm run build:standalone; do not edit. */";
  const newHeader = "/*! Pastafari Calendar v1.4.0 | standalone classic-script build | generated by npm run build:standalone; do not edit. */";
  const headerOk = current.startsWith(newHeader);
  const bodyUnchanged = old.startsWith(oldHeader) && current.slice(newHeader.length) === old.slice(oldHeader.length);
  standalone[relativePath] = { headerOk, bodyUnchanged };
  if (!headerOk) failures.push(`${relativePath} has wrong release banner`);
  if (!bodyUnchanged) failures.push(`${relativePath} changed beyond release banner before canonical rebuild verification`);
}
if (packageJson.version !== NEW_VERSION) failures.push("package.json version propagation failed");
if (lock.version !== NEW_VERSION || lock.packages?.[""]?.version !== NEW_VERSION) failures.push("package-lock version propagation failed");
if (!docsFacts.includes("Current package version: `1.4.0`")) failures.push("generated documentation version is stale");
if (!browserReadme.includes("לדוגמה `v1.4.0`")) failures.push("browser README release-tag example is stale");

const swSource = await readFile(path.join(ROOT, "docs/sw.js"), "utf8");
const pwaCurrent = await computeServiceWorkerCoreDigest(path.join(ROOT, "docs"), swSource);
const pwaBaseline = JSON.parse(await readFile(path.join(ROOT, "verification/pwa-cache-state.json"), "utf8"));
const pwaMatch = pwaBaseline.version === pwaCurrent.version && pwaBaseline.coreAssetsSha256 === pwaCurrent.coreAssetsSha256;
if (!pwaMatch) failures.push("PWA cache baseline is stale");

const historicalOccurrences = [];
async function scan(relativeDirectory = "") {
  const absolute = path.join(ROOT, relativeDirectory);
  for (const entry of await readdir(absolute, { withFileTypes: true })) {
    const rel = path.posix.join(relativeDirectory.replaceAll("\\", "/"), entry.name);
    if (entry.isDirectory()) {
      if ([".git", "node_modules", "artifacts", "verification"].includes(entry.name)) continue;
      await scan(rel);
      continue;
    }
    if (!entry.isFile() || entry.name === "SHA256SUMS.txt") continue;
    const info = await stat(path.join(ROOT, rel));
    if (info.size > 5 * 1024 * 1024) continue;
    let text;
    try { text = await readFile(path.join(ROOT, rel), "utf8"); } catch { continue; }
    if (!text.includes("1.3.0")) continue;
    text.split(/\r?\n/u).forEach((line, index) => { if (line.includes("1.3.0")) historicalOccurrences.push(`${rel}:${index + 1}:${line.trim()}`); });
  }
}
await scan();
const activeOldVersionAllow = [
  "UPDATE17-DELTA-MANIFEST.json:",
  "UPDATE18-DELTA-MANIFEST.json:",
  "UPDATE18-V3-DELTA-MANIFEST.json:",
  "UPDATE19-DELTA-MANIFEST.json:",
  "UPDATE20-DELTA-MANIFEST.json:",
  "test/docs-consistency.test.js:",
  "test/release-infrastructure.test.js:",
];
const historicalNarrativeOldVersionAllow = [
  (line) => line.startsWith("docs/AUTHORITATIVE-ENGINE-ARCHITECTURE.md:")
    && line.includes("Update 20 then merged the 1.3.0 -> 1.4.0 version/closure changes;"),
];
const suspicious = historicalOccurrences.filter((line) =>
  !activeOldVersionAllow.some((prefix) => line.startsWith(prefix))
  && !historicalNarrativeOldVersionAllow.some((allowed) => allowed(line))
);
if (suspicious.length) failures.push(`unclassified active 1.3.0 occurrences: ${suspicious.slice(0, 10).join(" | ")}`);

const artifact = {
  schema: "pastafari.update20.version-propagation.v1",
  generatedAt: new Date().toISOString(),
  status: failures.length ? "FAIL" : "PASS",
  oldVersion: "1.3.0",
  newVersion: NEW_VERSION,
  packageVersion: packageJson.version,
  lockVersions: { top: lock.version, rootPackage: lock.packages?.[""]?.version ?? null },
  standalone,
  pwa: { current: pwaCurrent, baseline: pwaBaseline, match: pwaMatch },
  historicalVersionOccurrencesRetained: historicalOccurrences.length,
  suspiciousOldVersionOccurrences: suspicious,
  versionApi: "package.json export",
  cliVersion: "NOT_APPLICABLE",
  failures,
};
await writeJson("version-propagation.json", artifact);
console.log(JSON.stringify(artifact, null, 2));
if (failures.length) process.exitCode = 1;
