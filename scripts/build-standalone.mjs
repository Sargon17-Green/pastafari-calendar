function hideThirdYearCeilingTurnFromStandaloneBundler() {
  return {
    name: "pastafari-hide-third-year-ceiling-turn",
    setup(buildContext) {
      buildContext.onLoad({ filter: /pastafari-calendar-core\.js$/ }, async (args) => {
        if (path.resolve(args.path) !== AUTHORITATIVE_CORE) return null;
        let source = await readFile(args.path, "utf8");
        if (source.split(STANDALONE_THIRD_DETOUR_IMPORT).length !== 2
          || source.split(STANDALONE_THIRD_DETOUR_INSTALL).length !== 2
          || source.split(STANDALONE_SECOND_DETOUR_INSTALL).length !== 2) {
          throw new Error("The third year-ceiling detour doorway changed; update the standalone scenic rewrite.");
        }
        source = source
          .replace(STANDALONE_THIRD_DETOUR_IMPORT, "")
          .replace(STANDALONE_THIRD_DETOUR_INSTALL, "")
          .replace(
            STANDALONE_SECOND_DETOUR_INSTALL,
            `${STANDALONE_SECOND_DETOUR_INSTALL}globalThis["${STANDALONE_SCENIC_LANDMARK_PROPERTY}"](PastafariCalendar, GateIndex);\n`,
          );
        return { contents: source, loader: "js" };
      });
    },
  };
}

function injectThirdYearCeilingTurnIntoStandaloneWorker(source) {
  // Do not bind this rewrite to esbuild's current minified identifier names.
  // Update 6 added the patch ledger, which legitimately renamed every symbol
  // around the old "Xr/Lr/Be" landmark.  The source transform above instead
  // plants a deliberately impossible global call between detour #2 and the
  // historical detour.  Minification may rename its arguments, but cannot
  // legally rewrite the hyphenated property into dot notation.
  const escapedProperty = STANDALONE_SCENIC_LANDMARK_PROPERTY.replace(/[.*+?^${}()|[\]\\]/gu, "\\$&");
  const landmarkPattern = new RegExp(
    `globalThis\\[["']${escapedProperty}["']\\]\\(([$\\w]+),([$\\w]+)\\);?`,
    "gu",
  );
  const matches = [...source.matchAll(landmarkPattern)];
  if (matches.length !== 1) {
    throw new Error(`Expected one Update 6 scenic landmark in bundled authoritative worker, found ${matches.length}.`);
  }
  const [wholeLandmark, CalendarConstructor, GateIndex] = matches[0];
  return source.replace(
    wholeLandmark,
    `${STANDALONE_THIRD_DETOUR_PAYLOAD}U5Install(${CalendarConstructor},${GateIndex});`,
  );
}

function staticWorkerEngineImport(filename) {
  const workerPath = path.join(BROWSER_DIR, filename);
  return {
    name: `pastafari-static-${filename}`,
    setup(buildContext) {
      buildContext.onLoad({ filter: /pastafari-(?:authoritative|fast)-worker\.js$/ }, async (args) => {
        if (path.resolve(args.path) !== workerPath) return null;
        let source = await readFile(args.path, "utf8");

        if (filename === "pastafari-authoritative-worker.js") {
          const urlDeclaration = "const CORE_MODULE_URL = new URL(\"./pastafari-calendar-core.js\", import.meta.url);";
          const dynamicImport = "const moduleNamespace = await import(CORE_MODULE_URL.href);";
          if (!source.includes(urlDeclaration) || !source.includes(dynamicImport)) {
            throw new Error("The authoritative Worker loader has changed; update the standalone build transform.");
          }
          source = source
            .replace(urlDeclaration, "import * as authoritativeModule from \"./pastafari-calendar-core.js\";")
            .replace(dynamicImport, "const moduleNamespace = authoritativeModule;");
        } else {
          const urlDeclaration = "const FAST_MODULE_URL = new URL(\"./pastafari-calendar-fast.js\", import.meta.url);";
          const dynamicImport = "const moduleNamespace = await import(FAST_MODULE_URL.href);";
          if (!source.includes(urlDeclaration) || !source.includes(dynamicImport)) {
            throw new Error("The fast Worker loader has changed; update the standalone build transform.");
          }
          source = source
            .replace(urlDeclaration, `import {
  FAST_IMPLEMENTATION_INFO,
  GregorianDate,
  PastafariCalendar,
  clearFastCache,
  convertJdnRange,
  getCutletView,
  getFastCacheStats,
} from "./pastafari-calendar-fast.js";

const fastModule = Object.freeze({
  FAST_IMPLEMENTATION_INFO,
  GregorianDate,
  PastafariCalendar,
  clearFastCache,
  convertJdnRange,
  getCutletView,
  getFastCacheStats,
});`)
            .replace(dynamicImport, "const moduleNamespace = fastModule;");
        }

        return { contents: source, loader: "js" };
      });
    },
  };
}

function removableReverseSideDoor() {
  return {
    name: "pastafari-unused-reverse-side-door",
    setup(buildContext) {
      buildContext.onLoad({ filter: /pastafari-calendar-fast\.js$/ }, async (args) => {
        if (path.resolve(args.path) !== FAST_ENGINE) return null;
        const source = await readFile(args.path, "utf8");
        const original = "const OTHER_CALENDAR_SIDE_DOOR = new URL(\"./pastafari-calendar-core.js\", import.meta.url);";
        if (!source.includes(original)) {
          throw new Error("The fast engine reverse side door has changed; update the standalone build audit.");
        }
        return {
          contents: source.replace(
            original,
            "const OTHER_CALENDAR_SIDE_DOOR = /* @__PURE__ */ (() => new URL(\"./pastafari-calendar-core.js\", \"file:///pastafari-calendar-fast.js\"))();",
          ),
          loader: "js",
        };
      });
    },
  };
}

async function bundleWorker(filename) {
  const plugins = [staticWorkerEngineImport(filename)];
  if (filename === "pastafari-authoritative-worker.js") {
    plugins.push(hideThirdYearCeilingTurnFromStandaloneBundler());
  }
  if (filename === "pastafari-fast-worker.js") plugins.push(removableReverseSideDoor());

  const result = await build({
    absWorkingDir: ROOT,
    bundle: true,
    charset: "utf8",
    entryPoints: [path.join(BROWSER_DIR, filename)],
    format: "iife",
    legalComments: "none",
    minify: true,
    platform: "browser",
    plugins,
    target: "es2020",
    treeShaking: true,
    write: false,
  });

  if (result.outputFiles.length !== 1) {
    throw new Error(`Expected one bundled Worker for ${filename}.`);
  }
  const source = result.outputFiles[0].text;
  return filename === "pastafari-authoritative-worker.js"
    ? injectThirdYearCeilingTurnIntoStandaloneWorker(source)
    : source;
}

function standaloneRouterAlias() {
  return {
    name: "pastafari-standalone-router",
    setup(buildContext) {
      buildContext.onResolve(
        { filter: /^\.\/pastafari-calendar-router\.js$/ },
        (args) => {
          const resolved = path.resolve(args.resolveDir, args.path);
          return resolved === STANDARD_ROUTER ? { path: STANDALONE_ROUTER } : null;
        },
      );
    },
  };
}

async function bundleStandalone({ filename, minify, workerSources }) {
  const result = await build({
    absWorkingDir: ROOT,
    banner: { js: BANNER },
    bundle: true,
    charset: "utf8",
    define: {
      __PASTAFARI_AUTHORITATIVE_WORKER_SOURCE__: JSON.stringify(workerSources.authoritative),
      __PASTAFARI_FAST_WORKER_SOURCE__: JSON.stringify(workerSources.fast),
    },
    entryPoints: [path.join(ROOT, "scripts", "standalone-entry.js")],
    format: "iife",
    globalName: "PastafariCalendarStandalone",
    legalComments: "none",
    minify,
    outfile: path.join(OUTPUT_DIR, filename),
    platform: "browser",
    plugins: [standaloneRouterAlias()],
    target: "es2020",
    treeShaking: true,
    write: false,
  });
  if (result.outputFiles.length !== 1) throw new Error(`Expected one output for ${filename}.`);
  return Buffer.from(result.outputFiles[0].contents);
}

function assertClassicScript(filename, source) {
  const forbidden = [
    ["static import", /\bimport\s+(?!\()/u],
    ["dynamic import", /\bimport\s*\(/u],
    ["import.meta", /\bimport\.meta\b/u],
    ["importScripts", /\bimportScripts\s*\(/u],
    ["module Worker", /\btype\s*:\s*["']module["']/u],
    ["runtime fetch", /\bfetch\s*\(/u],
  ];

  for (const [label, pattern] of forbidden) {
    if (pattern.test(source)) throw new Error(`${filename} unexpectedly contains ${label}.`);
  }
  if (!source.startsWith(BANNER)) throw new Error(`${filename} is missing the generated-file banner.`);
  if (!source.includes("PastafariCalendarStandalone")) {
    throw new Error(`${filename} does not expose the standalone namespace.`);
  }
}

function assertNoEnvironmentLeakage(filename, source) {
  const candidates = [ROOT, homedir()]
    .filter((value) => typeof value === "string" && value.length >= 4)
    .flatMap((value) => [value, value.replaceAll("\\", "/")]);
  for (const candidate of new Set(candidates)) {
    if (source.includes(candidate)) {
      throw new Error(`${filename} leaks a local build path: ${candidate}`);
    }
  }
}

async function buildAll() {
  const [authoritative, fast] = await Promise.all([
    bundleWorker("pastafari-authoritative-worker.js"),
    bundleWorker("pastafari-fast-worker.js"),
  ]);
  const workerSources = Object.freeze({ authoritative, fast });
  const outputs = new Map();

  for (const [filename, minify] of OUTPUTS) {
    const bytes = await bundleStandalone({ filename, minify, workerSources });
    const source = bytes.toString("utf8");
    assertClassicScript(filename, source);
    assertNoEnvironmentLeakage(filename, source);
    outputs.set(`browser/standalone/${filename}`, bytes);
  }
  return outputs;
}

export async function runStandaloneBuild({ verify = false, reportPath = null } = {}) {
  await mkdir(OUTPUT_DIR, { recursive: true });
  const first = await buildAll();
  const second = await buildAll();
  const reproducibility = assertReproducibleArtifacts(first, second, "standalone build");
  const artifacts = [];

  for (const record of reproducibility) {
    const bytes = first.get(record.path);
    const target = path.join(ROOT, ...record.path.split("/"));
    let canonicalSha256;
    if (verify) {
      let checkedIn;
      try {
        checkedIn = await readFile(target);
      } catch (error) {
        if (error?.code === "ENOENT") {
          throw new Error(`${record.path} is missing. Run npm run build:standalone.`);
        }
        throw error;
      }
      canonicalSha256 = assertGeneratedArtifactMatches(record.path, bytes, checkedIn);
    } else {
      await atomicWriteFile(target, bytes);
      canonicalSha256 = sha256Buffer(bytes);
    }
    artifacts.push({ ...record, canonicalSha256 });
  }

  const report = {
    version: PACKAGE.version,
    mode: verify ? "verify" : "prepare",
    esbuild: PACKAGE.devDependencies?.esbuild ?? null,
    artifacts,
  };

  if (reportPath) {
    await mkdir(path.dirname(path.resolve(reportPath)), { recursive: true });
    await atomicWriteFile(path.resolve(reportPath), `${JSON.stringify(report, null, 2)}\n`);
  }

  process.stdout.write(
    `[standalone] ${verify ? "VERIFY" : "BUILD"} PASS — ${artifacts.length} artifacts reproduced byte-for-byte\n`,
  );
  return report;
}

const invokedDirectly = path.resolve(process.argv[1] ?? "") === fileURLToPath(import.meta.url);
if (invokedDirectly) {
  const options = parseArguments(process.argv.slice(2));
  runStandaloneBuild(options).catch((error) => {
    console.error(`[standalone] FAIL\n${error?.stack ?? error}`);
    process.exitCode = 1;
  });
}
