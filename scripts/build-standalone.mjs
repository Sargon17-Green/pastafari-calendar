const STANDALONE_SCENIC_LANDMARK_PROPERTY = "pastafari-u6-scenic-third-detour-landmark";
const STANDALONE_SECOND_DETOUR_INSTALL =
  'installYearCeilingDetourDetour(PastafariCalendar, GateIndex);\n';
